#!/usr/bin/env python3
"""Builds everything that is generated from extensions/*/extension.json:

  manifests/<Name>.trex             -> points to GitHub Pages (share these with users / Tableau Server)
  manifests/localhost/<Name>.trex   -> points to http://localhost:<port> (testing on Tableau Desktop)
  extensions/<id>/dev/*-preview.html -> browser previews with sample data (no Tableau needed)
  extensions.json                   -> list of all extensions (used by the landing page)
  index.html                        -> landing page of the GitHub Pages site

Usage:
  python3 tools/build.py                 # uses githubUser from repo.json
  python3 tools/build.py <github-user>   # also saves it into repo.json
"""
import base64
import html
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXT_DIR = ROOT / 'extensions'
OUT = ROOT / 'manifests'
RESERVED_IDS = {'tooltip', 'detail'}      # Tableau adds these tiles itself
MAX_ENCODINGS = 4                          # Tableau limit for custom encodings
ROLES = {'continuous-measure', 'discrete-dimension', 'continuous-dimension', 'discrete-measure'}
DATA_TYPES = {'numeric', 'temporal', 'string', 'boolean'}


def esc(s):
    return html.escape(str(s), quote=True)


def load_repo():
    cfg = json.loads((ROOT / 'repo.json').read_text())
    if len(sys.argv) > 1:
        cfg['githubUser'] = sys.argv[1]
        (ROOT / 'repo.json').write_text(json.dumps(cfg, indent=2) + '\n')
    return cfg


def load_extensions():
    exts = []
    for f in sorted(EXT_DIR.glob('*/extension.json')):
        meta = json.loads(f.read_text())
        meta['id'] = f.parent.name
        validate(meta)
        exts.append(meta)
    return exts


def validate(m):
    where = f"extensions/{m['id']}/extension.json"
    for key in ('name', 'manifestName', 'version', 'entry', 'icon'):
        if not m.get(key):
            sys.exit(f'{where}: "{key}" is required')
    encs = m.get('encodings', [])
    if len(encs) > MAX_ENCODINGS:
        sys.exit(f'{where}: {len(encs)} encodings, Tableau allows at most {MAX_ENCODINGS} (Tooltip and Detail are built in)')
    ids = [e['id'] for e in encs]
    if len(ids) != len(set(ids)):
        sys.exit(f'{where}: encoding ids must be unique')
    for e in encs:
        if e['id'].lower() in RESERVED_IDS:
            sys.exit(f'{where}: encoding id "{e["id"]}" is reserved by Tableau')
        bad = set(e.get('roles', [])) - ROLES
        if bad:
            sys.exit(f'{where}: unknown role(s) {bad}')
        if e.get('dataType') and e['dataType'] not in DATA_TYPES:
            sys.exit(f'{where}: unknown dataType "{e["dataType"]}"')
    if not (EXT_DIR / m['id'] / m['icon']).exists():
        sys.exit(f'{where}: icon file "{m["icon"]}" not found')


def encoding_xml(e):
    x = [f'    <encoding id="{esc(e["id"])}">',
         f'      <display-name resource-id="{esc(e["id"])}-name">{esc(e["name"])}</display-name>']
    if e.get('dataType'):
        x += ['      <data-spec>', f'        <data-type>{e["dataType"]}</data-type>', '      </data-spec>']
    if e.get('roles'):
        x += ['      <role-spec>'] + [f'        <role-type>{r}</role-type>' for r in e['roles']] + ['      </role-spec>']
    if e.get('maxCount'):
        x.append(f'      <fields max-count="{int(e["maxCount"])}"/>')
    if e.get('icon'):
        x.append(f'      <encoding-icon token="{esc(e["icon"])}"/>')
    if e.get('tooltip'):
        x.append(f'      <tooltip resource-id="{esc(e["id"])}-tooltip">{esc(e["tooltip"])}</tooltip>')
    x.append('    </encoding>')
    return '\n'.join(x)


def manifest(m, repo, url, local):
    a = repo['author']
    icon = base64.b64encode((EXT_DIR / m['id'] / m['icon']).read_bytes()).decode()
    ext_id = f"{repo['idPrefix']}.{re.sub(r'[^a-z0-9]', '', m['id'].lower())}" + ('.dev' if local else '')
    name = m['name'] + (' (dev)' if local else '')
    encs = '\n'.join(encoding_xml(e) for e in m.get('encodings', []))
    res = [f'    <resource id="name"><text locale="en_US">{esc(name)}</text></resource>']
    for e in m.get('encodings', []):
        res.append(f'    <resource id="{esc(e["id"])}-name"><text locale="en_US">{esc(e["name"])}</text></resource>')
        if e.get('tooltip'):
            res.append(f'    <resource id="{esc(e["id"])}-tooltip"><text locale="en_US">{esc(e["tooltip"])}</text></resource>')
    menu = ('    <!-- Adds the "Format Extension" button (calls the configure callback) -->\n'
            '    <context-menu>\n      <configure-context-menu-item />\n    </context-menu>\n') if m.get('formatDialog') else ''
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/build.py from extensions/{m['id']}/extension.json. Do not edit by hand. -->
<manifest manifest-version="0.1" xmlns="http://www.tableau.com/xml/extension_manifest">
  <worksheet-extension id="{ext_id}" extension-version="{esc(m['version'])}">
    <default-locale>en_US</default-locale>
    <name resource-id="name"/>
    <description>{esc(m.get('description', ''))}</description>
    <author name="{esc(a['name'])}" email="{esc(a['email'])}" organization="{esc(a['organization'])}" website="{esc(a['website'])}"/>
    <min-api-version>{m.get('minApiVersion', '1.11')}</min-api-version>
    <source-location>
      <url>{esc(url)}</url>
    </source-location>
    <icon>{icon}</icon>
    <permissions>
      <permission>full data</permission>
    </permissions>
{menu}{encs}
  </worksheet-extension>
  <resources>
{chr(10).join(res)}
  </resources>
</manifest>
'''


def stamp_versions(m):
    """Cache-busting: every local .js/.css reference in the extension's pages gets ?v=<version>,
    and the page gets <meta name="ext-version">. Tableau (and GitHub Pages) cache files hard;
    a new version number makes them fetch the new code."""
    ext = EXT_DIR / m['id']
    ver = m['version']
    ref = re.compile(r'((?:src|href)="(?:\./|\.\./)[^"?]+\.(?:js|css))(?:\?v=[^"]*)?"')
    for page in ext.glob('*.html'):
        html = page.read_text()
        out = ref.sub(lambda mm: f'{mm.group(1)}?v={ver}"', html)
        meta = f'<meta name="ext-version" content="{ver}" />'
        if 'name="ext-version"' in out:
            out = re.sub(r'<meta name="ext-version" content="[^"]*" />', meta, out)
        else:
            out = out.replace('<meta charset="utf-8" />', '<meta charset="utf-8" />\n  ' + meta, 1)
        if out != html:
            page.write_text(out)


def build_previews(m):
    """dev/<page>-preview.html = the real page with the Tableau library swapped for the mock.
    A <base href="../"> keeps every relative path of the real page working unchanged."""
    ext = EXT_DIR / m['id']
    dev = ext / 'dev'
    dev.mkdir(exist_ok=True)
    lib_tag = re.compile(r'<script[^>]*tableau\.extensions[^>]*></script>')
    for i, page in enumerate(m.get('previewPages', [m['entry']])):
        src = (ext / page).read_text()
        if i == 0:   # main viz page: mock API + this extension's sample data
            mock = ('<script src="../../shared/dev/mock-tableau.js"></script>\n'
                    '  <script src="dev/scenarios.js"></script>')
        else:        # dialog pages run inside the mock's overlay iframe
            mock = '<script>window.tableau = window.parent.__mockDialogTableau;</script>'
        if not lib_tag.search(src):
            sys.exit(f'extensions/{m["id"]}/{page}: no tableau.extensions script tag found')
        out = lib_tag.sub(mock, src, count=1)
        out = out.replace('<head>', '<head>\n  <base href="../" />\n  <!-- GENERATED preview (tools/build.py): sample data instead of Tableau -->', 1)
        out = re.sub(r'<title>(.*?)</title>', r'<title>\1 (preview)</title>', out, count=1)
        name = 'preview.html' if i == 0 else page.replace('.html', '-preview.html')
        (dev / name).write_text(out)


def landing(exts, repo):
    base = f"https://{repo['githubUser']}.github.io/{repo['repoName']}"
    cards = []
    for m in exts:
        icon = base64.b64encode((EXT_DIR / m['id'] / m['icon']).read_bytes()).decode()
